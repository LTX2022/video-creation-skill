import {writeTextIfChanged} from "./stable-generated-file";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, "..");
const TIMING_PATH = resolve(ROOT, "timing-manifest.json");
const OUT_PATH = resolve(ROOT, "src/video/render-timing.generated.ts");
const AUDIO_DIR = resolve(ROOT, "public/audio");

interface SubtitleCue {
  startMs: number;
  endMs: number;
  text: string;
  chunks: string[];
}

interface TimingManifestStep {
  chapter: string;
  step: number;
  text: string;
  subtitleChunks: string[];
  subtitleCues?: SubtitleCue[];
  audio: string | null;
  advanceAtMs: number;
  durationInFrames?: number;
}

if (!existsSync(TIMING_PATH)) {
  console.error("x timing-manifest.json not found. Run: npm run build-timing");
  process.exit(1);
}

function readJson(path: string): any {
  return JSON.parse(readFileSync(path, "utf8").replace(/^\uFEFF/, ""));
}

const manifest = readJson(TIMING_PATH);
const steps = (manifest.steps ?? []) as TimingManifestStep[];
const fps = Number.isFinite(Number(manifest.fps)) && Number(manifest.fps) > 0 ? Number(manifest.fps) : 60;

let cursor = 0;
const renderSteps = steps.map((step) => {
  const durationInFrames = Number.isInteger(step.durationInFrames) && step.durationInFrames! > 0
    ? step.durationInFrames! : Math.max(1, Math.ceil((step.advanceAtMs / 1000) * fps));
  const item = {
    chapter: step.chapter,
    stepIndex: step.step - 1,
    startFrame: cursor,
    durationInFrames,
    text: step.text ?? "",
    subtitleChunks: step.subtitleChunks ?? [],
    subtitleCues: step.subtitleCues ?? [],
    audio: step.audio && existsSync(join(AUDIO_DIR, step.audio)) ? `audio/${step.audio}` : null,
  };
  cursor += durationInFrames;
  return item;
});

const source = `// Auto-generated by scripts/build-render-timing.ts.
// Do not edit manually. Run 'npm run render:timing' after audio or narration changes.

export interface RenderStepTiming {
  chapter: string;
  stepIndex: number;
  startFrame: number;
  durationInFrames: number;
  text: string;
  subtitleChunks: string[];
  subtitleCues: {
    startMs: number;
    endMs: number;
    text: string;
    chunks: string[];
  }[];
  audio: string | null;
}

export const STEP_TIMINGS: RenderStepTiming[] = ${JSON.stringify(renderSteps, null, 2)};
export const TOTAL_FRAMES = ${cursor};
`;

const changed = writeTextIfChanged(OUT_PATH, source);
console.error(`v ${changed ? "wrote" : "unchanged"} ${OUT_PATH}`);
console.error(`  total frames: ${cursor} (${(cursor / fps).toFixed(1)}s @ ${fps}fps)`);
